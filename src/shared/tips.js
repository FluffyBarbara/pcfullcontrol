  /** Проставляет data-tip всем элементам, у которых его ещё нет. */
  function apply(map, scope) {
    const doc = scope || document;
    for (const [sel, text] of Object.entries(map)) {
      doc.querySelectorAll(sel).forEach((n) => { if (!n.dataset.tip) n.dataset.tip = text; });
    }
    doc.querySelectorAll('[data-act], [data-power]').forEach((n) => {
      const name = n.dataset.act || n.dataset.power;
      if (!n.dataset.tip && ACTIONS[name]) n.dataset.tip = ACTIONS[name];
    });
    // Обычные title превращаем в красивые подсказки (без двойной системной подсказки)
    doc.querySelectorAll('button[title], [role="button"][title]').forEach((n) => {
      if (!n.dataset.tip) n.dataset.tip = n.getAttribute('title');
      n.removeAttribute('title');
    });
  }

  const api = { ACTIONS, PC, MOBILE, apply };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.Tips = api;
